#include <cstdint>
#include <optional>
#include <string>
#include <vector>

namespace lazyluno {

enum class StreamType { Video, Audio, Muxed };
enum class ContainerFormat { MP4, WEBM, TS, Unknown };

struct Stream {
    int             itag            = 0;
    StreamType      type            = StreamType::Muxed;
    ContainerFormat container       = ContainerFormat::Unknown;

    std::string     url;            // deciphered, ready to fetch
    std::string     mimeType;       // e.g. "video/mp4; codecs=\"avc1.640028\""
    std::string     codec;          // e.g. "avc1.640028" or "opus"

    // Video-specific
    int             width           = 0;
    int             height          = 0;
    double          fps             = 0.0;
    std::string     qualityLabel;   // "1080p", "720p60", etc.

    // Audio-specific
    int             audioSampleRate = 0;
    int             audioChannels   = 0;
    int             audioBitrate    = 0;   // bps

    // Both
    int64_t         bitrate         = 0;   // bps
    int64_t         contentLength   = 0;   // bytes, 0 if unknown
    int64_t         approxDurationMs= 0;

    // DASH chunked — use Range header for partial fetching
    bool            isDashStream    = false;
    int             indexStart      = 0;
    int             indexEnd        = 0;
    int             initStart       = 0;
    int             initEnd         = 0;

    bool isVideoOnly() const { return type == StreamType::Video; }
    bool isAudioOnly() const { return type == StreamType::Audio; }
    bool isMuxed()     const { return type == StreamType::Muxed;  }
};

struct SubtitleTrack {
    std::string langCode;   // "en", "fr", etc.
    std::string langName;
    std::string url;
    bool        isAutoGenerated = false;
};

} // namespace lazyluno
